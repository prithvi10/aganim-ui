type ProfileJsonLdProps = {
  schemas: object[];
};

export function ProfileJsonLd({ schemas }: ProfileJsonLdProps) {
  return (
    <>
      {schemas.map((schema, index) => (
        <script
          key={index}
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: JSON.stringify(schema) }}
        />
      ))}
    </>
  );
}
